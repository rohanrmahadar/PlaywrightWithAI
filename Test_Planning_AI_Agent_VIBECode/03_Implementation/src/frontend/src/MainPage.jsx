import React, { useState } from 'react';
import { marked } from 'marked';
import DOMPurify from 'dompurify';
import { api } from './api.js';

const KEY_RE = /^[A-Z][A-Z0-9_]+-\d+$/;

export default function MainPage({ config, goToSettings }) {
  const [issueKey, setIssueKey] = useState('');
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');
  const [result, setResult] = useState(null);

  async function submit(e) {
    e.preventDefault();
    if (loading) return; // prevent duplicate submissions
    const key = issueKey.trim().toUpperCase();
    if (!KEY_RE.test(key)) {
      setError('Enter a valid Jira issue ID, e.g. PROJ-123.');
      return;
    }
    setLoading(true);
    setError('');
    try {
      setResult(await api('/generate', { method: 'POST', body: { issueKey: key, config } }));
    } catch (err) {
      setError(err.message); // keep the input so the user can retry
    } finally {
      setLoading(false);
    }
  }

  return (
    <main className="page main-page">
      <section className="box reply" aria-live="polite">
        {loading && <p className="state">Fetching {issueKey.trim().toUpperCase()} from Jira and generating the test plan…</p>}
        {!loading && error && <p className="state error">{error}{/configur|authentication|API key/i.test(error) && <> <button className="linkbtn" onClick={goToSettings}>Open Settings</button></>}</p>}
        {!loading && !error && !result && <p className="state muted">Reply with Test Plan</p>}
        {!loading && result && (
          <>
            <div className="source">
              Source: <a href={result.issue.url} target="_blank" rel="noreferrer">{result.issue.key}</a> — {result.issue.summary}
              <span className="muted"> · Generated by {result.model} · AI draft, review before use</span>
              {!result.issue.acceptanceCriteriaFound && <div className="warn">No acceptance criteria found in this issue.</div>}
              {result.missingSections.length > 0 && (
                <div className="warn">Missing template sections: {result.missingSections.join(', ')}</div>
              )}
            </div>
            <article className="plan" dangerouslySetInnerHTML={{ __html: DOMPurify.sanitize(marked.parse(result.markdown)) }} />
          </>
        )}
      </section>
      <form className="box prompt" onSubmit={submit}>
        <input
          value={issueKey}
          onChange={(e) => setIssueKey(e.target.value)}
          placeholder="Prompt (JIRA Ticket) e.g. PROJ-123"
          aria-label="Jira issue ID"
          disabled={loading}
        />
        <button className="btn primary" disabled={loading || !issueKey.trim()}>
          {loading ? 'Generating…' : 'Generate'}
        </button>
      </form>
    </main>
  );
}
